#ifndef _CODE_H_
#define _CODE_H_

#include "headfile.h"
#include "pid.h"

/*===================================================================================================================
 *  v3 控制方案（全部重写）
 *  ---------------------------------------------------------------------------------------------------------------
 *  电感 ：单次采集 -> 自适应窗口去极值平均 -> 一阶低通 -> 归一化 -> 差比和
 *  曲率 ：curv = 0.3*fe + 0.4*fd + 0.3*fv     （fe 来自 |error|，fd 来自 |Δerror|，fv 来自竖向电感和）
 *  方向 ：error * K  ->  位置式 PID  ->  舵机         （K = 1 + (K_MAX-1)*curv）
 *  速度 ：编码器 -> 一阶低通 -> 增量式 PID -> 两轮同速（无差速）
 *  圆环 ：开环定时强制打角
 *==================================================================================================================*/

/*----------------------------- 电感通道 -----------------------------*/
/*  adc1 = P0.0 = LX 左横
    adc2 = P0.1 = LY 左竖
    adc3 = P0.2 = RY 右竖
    adc4 = P0.3 = RX 右横   */
#define ADC_LEFTX_CHANNEL       ADC_P00
#define ADC_RIGHTX_CHANNEL      ADC_P03
#define ADC_LEFTY_CHANNEL       ADC_P01
#define ADC_RIGHTY_CHANNEL      ADC_P02

/*----------------------------- 标定值（归一化用） -----------------------------*/
#define LX_MAX      3300
#define LX_MIN      9
#define RX_MAX      3000
#define RX_MIN      0
#define LY_MAX      3600
#define LY_MIN      0
#define RY_MAX      3580
#define RY_MIN      0

/*===================================================================================================================
 *  1. 电感处理：自适应窗口去极值平均 + 一阶低通
 *==================================================================================================================*/
#define WIN_STRAIGHT        5       /* 直道窗口：采 5 个，去掉最大最小，剩 3 个平均 */
#define WIN_CURVE           3       /* 弯道窗口：采 3 个，去掉最大最小，剩 1 个（中值） */
#define ALPHA_STRAIGHT      0.15f   /* 直道低通系数：小 = 滤得重、抖动小、响应慢 */
#define ALPHA_CURVE         0.50f   /* 弯道低通系数：大 = 滤得轻、响应快 */
#define WIN_UP              0.45f   /* curv 高于此值 -> 切到 3 次窗口 */
#define WIN_DOWN            0.35f   /* curv 低于此值 -> 切回 5 次窗口（滞回） */

/*===================================================================================================================
 *  2. 曲率系数 curv（0~1）
 *==================================================================================================================*/
#define E_FULL              60.0f   /* |error| 达到它就 fe=1（满弯） */
#define DE_FULL              5.0f   /* |Δerror| 每 5ms 达到它就 fd=1 */
#define DE_DEAD              3      /* Δerror 死区：|Δerror| < 3 当作 0 */
#define W_E                  0.3f   /* 当前偏差权重 */
#define W_D                  0.4f   /* 偏差变化权重 */
#define W_V                  0.3f   /* 竖向电感和权重（提前预判弯道） */

#define SV_LO                400    /* 竖向和低于它 = 直道（直道实测最大 300） */
#define SV_HI               1500    /* 竖向和高于它 = 满弯（弯道实测 1500 以上） */
#define CROSS_V_TH          4000    /* 竖向和 >= 此值 -> 十字，curv 强制 0（不打角） */
#define K_MAX                5.0f   /* 预判增益上限：K = 1 + (K_MAX-1)*curv */

/*===================================================================================================================
 *  3. 方向环（位置式 PID）
 *==================================================================================================================*/
#define SERVO_KP             2.6f
#define SERVO_KI             0.0f
#define SERVO_KD             7.0f
#define SERVO_MAX_I        100.0f
#define SERVO_MAX_OUT      400.0f

/* 输入死区：|error*K| 小于它 -> 输出 0（直道防抖；舵机死区补偿已整段删除） */
#define E_DEAD               8.0f

/*===================================================================================================================
 *  4. 速度环（增量式 PID，两轮同速，无差速）
 *==================================================================================================================*/
#define SPEED_KP            40.0f
#define SPEED_KI            60.0f
#define SPEED_KD             0.0f
#define SPEED_MAX_OUT    10000.0f
#define SPEED_NO_REVERSE       1       /* 1 = 输出不允许正转（防过冲反转） */

#define TARGET_SPEED_BASE     -7       /* 每 5ms 目标路程（脉冲），负数 = 前进 */
#define SPEED_SAMPLE_DIV       2       /* 2 x 5ms = 10ms 做一次速度环 */
#define DEAD_SPEED             1       /* 速度死区（10ms 累加单位） */
#define ENC_ALPHA           0.40f      /* 编码器一阶低通系数 */

/*===================================================================================================================
 *  5. 圆环（开环定时强制打角）
 *==================================================================================================================*/
#define RING_FORCE_ENABLE      1
#define FORCE_START_TICK     960       /* 960 x 5ms = 4.8 秒开始进环 */
#define FORCE_TIME_TICK      300       /* 300 x 5ms = 1.5 秒左打 */
#define FORCE_DUTY           350       /* 左打 duty（650 = 中位） */

/*===================================================================================================================
 *  6. 显示
 *==================================================================================================================*/
#define LCD_DEBUG              1

/*===================================================================================================================
 *  类型与变量
 *==================================================================================================================*/
typedef struct
{
    ADCN_enum ch;
    uint16    max;
    uint16    min;
    uint16    buf[WIN_STRAIGHT];   /* 最近 5 次采样 */
    uint8     idx;                 /* 写指针 */
    uint8     cnt;                 /* 已采次数 */
    float     lpf;                 /* 低通输出 */
    uint16    val;                 /* 本次滤波后的原始值 */
} adc_proc_t;

extern adc_proc_t ch_lx, ch_rx, ch_ly, ch_ry;

extern PID servo_pid;              /* 方向环（位置式） */
extern PID left_pid, right_pid;    /* 速度环（增量式） */

extern uint16 run_tick;            /* 上电后经过的 5ms 数 */

extern uint16 lh, rh, lv, rv;      /* 四路归一化 0~100 */
extern uint16 raw_lx, raw_rx, raw_ly, raw_ry;   /* 四路滤波后的原始值 */
extern uint16 sv_now, ss_now;      /* 竖向和 / 横向和（原始） */
extern int16  error;               /* 差比和偏差 -100~100 */
extern int16  error_last;          /* 上一周期偏差 */
extern int16  de_now;              /* Δerror */
extern float  curv;                /* 曲率系数 0~1 */
extern float  k_pred;              /* 预判增益 1~K_MAX */
extern int16  err_in;              /* 进 PID 的偏差 = error * k_pred */
extern int16  servo_out;           /* 方向环输出 */
extern int16  servo_duty;          /* 最终下发的舵机 duty */
extern int16  speed_l, speed_r;    /* 左右轮本周期脉冲 */
extern float  enc_f_l, enc_f_r;    /* 速度环滤波后速度（10ms 脉冲） */
extern int16  enc_acc_l, enc_acc_r;
extern uint8  spd_div;
extern int16  motor_l, motor_r;    /* 最终下发的电机占空比 */
extern uint8  curve_flag;          /* 1 = curv 超过 WIN_UP（只用于显示） */

/*===================================================================================================================
 *  函数
 *==================================================================================================================*/
uint16 adc_proc(adc_proc_t *c);          /* 采一次 -> 窗口去极值 -> 低通 -> 归一化 */
int16  calc_error(uint16 left, uint16 right);
void   curv_update(void);                /* 更新 curv / k_pred */
void   ring_force(void);                 /* 圆环开环强制打角 */

#endif
